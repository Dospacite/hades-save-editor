"use strict";

// Regenerates public/js/hades2-game-data.js from the installed Hades II.
// Run it after a game patch, then run `npm run audit-game` to see what changed.
//
//   npm run update-game-data -- [--game-dir <path>]

const { existsSync, readFileSync, writeFileSync } = require("node:fs");
const { join, relative, resolve } = require("node:path");
const { extractHades2 } = require("./lib/hades2-extract");
const { buildEditorData } = require("./lib/hades2-editor-data");
const { findGameDir } = require("./lib/game-paths");

const projectRoot = resolve(__dirname, "..");
const publicDir = join(projectRoot, "public");
const outputPath = join(publicDir, "js", "hades2-game-data.js");

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--game-dir") args.gameDir = argv[++i];
    else if (argv[i] === "--help" || argv[i] === "-h") args.help = true;
    else throw new Error(`Unknown argument: ${argv[i]}`);
  }
  return args;
}

// One item per line keeps diffs after a patch easy to read.
function stringify(value, indent = "") {
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.every((item) => item === null || typeof item !== "object")) return JSON.stringify(value);
    return `[\n${value.map((item) => `${inner}${JSON.stringify(item)}`).join(",\n")}\n${indent}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value);
    if (!entries.length) return "{}";
    const nested = (item) => item && typeof item === "object"
      && (Array.isArray(item) || Object.values(item).some((v) => v && typeof v === "object") || Object.keys(item).length > 6);
    return `{\n${entries.map(([key, item]) => `${inner}${JSON.stringify(key)}: ${nested(item) ? stringify(item, inner) : JSON.stringify(item)}`).join(",\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}

function render(data) {
  return [
    "// Generated by `npm run update-game-data` from the installed Hades II.",
    "// Don't edit by hand. Rerun the script after a game patch.",
    "(function attachGameData(global) {",
    "  \"use strict\";",
    "",
    `  global.HadesGameData = Object.freeze({ hades2: ${stringify(data).replace(/\n/g, "\n  ")} });`,
    "})(typeof globalThis !== \"undefined\" ? globalThis : window);",
    "",
  ].join("\n");
}

function summarize(previous, next) {
  const lines = [];
  for (const key of Object.keys(next)) {
    if (!Array.isArray(next[key]) || next[key].some((item) => typeof item === "number")) continue;
    const id = (item) => (typeof item === "string" ? item : item.key);
    const before = new Set((previous?.[key] || []).map(id));
    const added = next[key].map(id).filter((item) => !before.has(item));
    const after = new Set(next[key].map(id));
    const removed = [...before].filter((item) => !after.has(item));
    if (added.length || removed.length) {
      lines.push(`  ${key}: ${added.length ? `+${added.join(", +")}` : ""}${added.length && removed.length ? " " : ""}${removed.length ? `-${removed.join(", -")}` : ""}`);
    }
  }
  return lines;
}

function readPrevious() {
  if (!existsSync(outputPath)) return null;
  const context = {};
  try {
    new Function("globalThis", readFileSync(outputPath, "utf8"))(context);
    return context.HadesGameData?.hades2 || null;
  } catch {
    return null;
  }
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log("Usage: npm run update-game-data -- [--game-dir <path>]");
    return;
  }
  const gameDir = args.gameDir || findGameDir();
  if (!gameDir) throw new Error("Couldn't find Hades II. Pass --game-dir or set HADES2_DIR.");

  const game = extractHades2(gameDir);
  if (game.warnings.length) {
    console.warn(`${game.warnings.length} parse warnings:\n${game.warnings.slice(0, 10).join("\n")}`);
  }
  const data = buildEditorData(game, { publicDir });
  const previous = readPrevious();
  writeFileSync(outputPath, render(data));

  const changes = previous ? summarize(previous, data) : [];
  console.log(`Read ${game.scriptsLoaded} Lua files from ${gameDir}.`);
  console.log(changes.length ? `Changes:\n${changes.join("\n")}` : "No item changes.");
  const missingIcons = [...data.resources, ...data.keepsakes].filter((item) => !item.icon).map((item) => item.key);
  if (missingIcons.length) console.log(`No icon yet for: ${missingIcons.join(", ")}`);
  console.log(`Wrote ${relative(process.cwd(), outputPath)}.`);
}

main();
